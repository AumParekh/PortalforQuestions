def load_blocks():
    with open(BLOCKS) as fh:
        d = json.load(fh)
    out = {}
    for rid, r in d['readings'].items():
        for o in r.get('objectives', []):
            for b in o.get('blocks', []):
                sf, sl = b.get('source_file'), b.get('source_line')
                if sf and sl:
                    text = ' '.join(str(b.get(k, '')) for k in ('plain_text', 'body_latex', 'rows', 'title'))
                    out.setdefault(sf, []).append((sl, b['id'], text.lower()))
    for v in out.values():
        v.sort()
    return out


def find_block(blocks, sf, line, keywords):
    """Nearest preceding block (within 40 lines) whose text contains a keyword, else None."""
    cands = [b for b in blocks.get(sf, []) if b[0] <= line and line - b[0] <= 40]
    for sl, bid, text in reversed(cands):
        if any(k.lower() in text for k in keywords):
            return bid
    return None


def main():
    blocks = load_blocks()
    node_ids = [n['id'] for n in NODES]
    out_nodes = []
    for n in NODES:
        ev = []
        for field in ('introduced', 'restricted', 'responding_to'):
            for i, (t, e) in enumerate(n[field]):
                ev.append(dict(field=field, index=i, **e))
        links = []
        for pid, kind, basis, e in n['parents']:
            d = dict(parent=pid, kind=kind, basis=basis)
            if e:
                d.update(source_file=e['source_file'], source_line=e['source_line'],
                         keywords=e['keywords'])
            links.append(d)
        src = n['src']
        out_nodes.append({
            'id': n['id'], 'name': n['name'], 'short': n['short'], 'year': n['year'],
            'year_source': (dict(source_file=n['year_ev']['source_file'],
                                 source_line=n['year_ev']['source_line'],
                                 keywords=n['year_ev']['keywords'])
                            if n['year_ev'] else None),
            'year_note': (None if n['year'] is not None else
                          'Not dated in the notes; placed by its parents/lineage only.'),
            'lineage': n['lineage'],
            'parents': [p[0] for p in n['parents']],
            'parent_links': links,
            'reading_ids': n['readings'],
            'source_file': src['source_file'], 'source_line': src['source_line'],
            'source_keywords': src['keywords'],
            'source_block': find_block(blocks, src['source_file'], src['source_line'],
                                       src['keywords']),
            'introduced': [t for t, _ in n['introduced']],
            'restricted': [t for t, _ in n['restricted']],
            'responding_to': [t for t, _ in n['responding_to']],
            'evidence': ev,
            'summary': n['summary'],
            'aliases': n['aliases'],
            'related': n['related'],
        })
    changes = []
    counters = {}
    for rid, nid, text, decoys, why, e in CHANGES:
        counters[rid] = counters.get(rid, 0) + 1
        changes.append({
            'id': 'fn-%s-%02d' % (rid, counters[rid]), 'reading_id': rid, 'text': text,
            'node': nid, 'decoys': decoys, 'why': why,
            'source_file': e['source_file'], 'source_line': e['source_line'],
            'keywords': e['keywords'],
            'source_block': find_block(blocks, e['source_file'], e['source_line'], e['keywords']),
        })
    pairs = []
    pc = {}
    for rid, a, b, diffs in PAIRS:
        pc[rid] = pc.get(rid, 0) + 1
        pairs.append({
            'id': 'fnp-%s-%02d' % (rid, pc[rid]), 'a': a, 'b': b, 'reading_id': rid,
            'differences': [t for t, _ in diffs],
            'difference_sources': [dict(index=i, **e) for i, (_, e) in enumerate(diffs)],
        })
    doc = {
        'version': 1,
        'mechanic': 'framework-navigator',
        'notes': ('Parent kinds: explicit = the notes state the link; component = the parent '
                  'introduced the child; sequence = chronological predecessor in the lineage. '
                  'year null = the notes do not date the framework.'),
        'lineages': [{'id': i, 'label': l} for i, l in LINEAGES],
        'nodes': out_nodes,
        'changes': changes,
        'pairs': pairs,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as fh:
        json.dump(doc, fh, indent=1, ensure_ascii=False)
        fh.write('\n')
    print('wrote %s: %d nodes, %d changes, %d pairs' % (
        os.path.relpath(OUT, ROOT), len(out_nodes), len(changes), len(pairs)))
    assert len(set(node_ids)) == len(node_ids)


if __name__ == '__main__':
    main()
