def rid_of(path):
    """30_MR_MR11.tex -> MR-11; LR_LTR -> LTR-n; OR_ORR -> ORR-n; IM -> IM-n."""
    m = re.search(r'\d+_([A-Z]+)_([A-Z]+?)(\d+)\.tex$', path)
    return '%s-%s' % (m.group(2), m.group(3))


def E(f, line, *kw):
    return {'source_file': F[f], 'source_line': line, 'keywords': list(kw)}


